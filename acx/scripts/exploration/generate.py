#!/usr/bin/env python3
"""Project ACX: dungeon exploration markers from a marker plan.

/acxmarkerplan (on Preview, with the dungeon meshes built) writes <instance data>/Pathfinding/marker-plan.json:
each dungeon's walkable spot farthest from its entrance. This turns the plan into
  acx/Content/exploration/markers.json          each dungeon's name, level, marker distance, entrance and its common
                                                monsters, for the server (Managers/AcxExploration.cs, AcxContracts.cs)
  acx/Content/exploration/10-dungeon-markers.sql the marker weenie (900500) and one marker per dungeon
Run: python3 acx/scripts/exploration/generate.py ~/acx-data/preview/Pathfinding/marker-plan.json
"""
import collections, json, os, statistics, subprocess, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
plan = [{k.lower(): v for k, v in d.items()} for d in json.load(open(os.path.expanduser(sys.argv[1])))]
MIN_DISTANCE = 30   # metres: a closer "farthest point" means the dungeon goes on through an inner portal into another landblock
ok = [d for d in plan if d.get("status") == "ok" and d["distance"] >= MIN_DISTANCE]
short = sum(1 for d in plan if d.get("status") == "ok" and d["distance"] < MIN_DISTANCE)

out_dir = os.path.join(root, "Content", "exploration")
os.makedirs(out_dir, exist_ok=True)

def query(sql):
    r = subprocess.run(["docker", "exec", "-i", "acx-preview-db-1", "sh", "-c", 'exec mysql -N -B -uroot -p"$MYSQL_ROOT_PASSWORD" ace_world 2>/dev/null'],
                       input=sql, capture_output=True, text=True, check=True)
    return [l.split("\t") for l in r.stdout.splitlines() if l]

# the monsters each dungeon spawns (placed, or through generators), for kill contracts
weenies = {int(w): (int(t), n, int(lv)) for w, t, n, lv in query(
    "SELECT w.class_Id, w.type, IFNULL(n.value,''), IFNULL(l.value,0) FROM weenie w LEFT JOIN weenie_properties_string n ON n.object_Id=w.class_Id AND n.type=1 "
    "LEFT JOIN weenie_properties_int l ON l.object_Id=w.class_Id AND l.type=25;")}
unattackable = {int(r[0]) for r in query("SELECT object_Id FROM weenie_properties_bool WHERE type=19 AND value=0;")}
generators = collections.defaultdict(list)
for o, w in query("SELECT object_Id, weenie_Class_Id FROM weenie_properties_generator;"):
    generators[int(o)].append(int(w))
lbs = ",".join(str(int(d["landblock"], 16)) for d in ok)
placed = collections.defaultdict(list)
for w, c in query(f"SELECT weenie_Class_Id, obj_Cell_Id >> 16 FROM landblock_instance WHERE (obj_Cell_Id >> 16) IN ({lbs});"):
    placed[int(c)].append(int(w))

def spawns(wcid, depth=0):
    t = weenies.get(wcid)
    if not t or depth > 3:
        return []
    out = [wcid] if t[0] == 10 and t[2] > 0 and wcid not in unattackable else []
    for g in generators.get(wcid, []):
        out += spawns(g, depth + 1)
    return out

def monsters(lb, level):
    counts = collections.Counter(m for w in placed[lb] for m in spawns(w))
    picks = [(w, n) for w, n in counts.items() if n >= 5 and level * 0.6 <= weenies[w][2] <= level * 1.6 + 10]
    return [{"wcid": w, "name": weenies[w][1], "count": n} for w, n in sorted(picks, key=lambda x: -x[1])[:4]]

entrances = {e["landblock"]: e for e in json.load(open(os.path.join(os.path.dirname(os.path.expanduser(sys.argv[1])), "marker-input.json")))}
dungeons = []
for d in ok:
    e = entrances[d["landblock"]]
    dungeons.append({"landblock": d["landblock"], "name": d["name"], "level": d["level"], "distance": round(d["distance"]),
                     "entrance": {"cell": e["cell"], "x": e["x"], "y": e["y"], "z": e["z"]},
                     "monsters": monsters(int(d["landblock"], 16), d["level"])})
json.dump(dungeons, open(os.path.join(out_dir, "markers.json"), "w"), indent=1)

rows = []
for d in ok:
    lb = int(d["landblock"], 16)
    guid = 0x70000000 | (lb << 12) | 0xF30
    rows.append(f"    (0x{guid:08X}, 900500, 0x{d['cell']:08X}, {d['x']:.3f}, {d['y']:.3f}, {d['z'] + 0.05:.3f}, 1, 0, 0, 0, 0)"
                f",   -- {d['name']} (level {d['level']}, {d['distance']:.0f} m in)")
rows[-1] = rows[-1].replace(",   --", ";   --", 1)

sql = f"""-- Project ACX: dungeon exploration markers (Managers/AcxExploration.cs, JJ 2026-11-12). GENERATED by
-- acx/scripts/exploration/generate.py from a /acxmarkerplan run: do not edit by hand, re-plan and regenerate.
-- One marker per dungeon with an entrance from the outside world ({len(ok)} dungeons), at the walkable spot farthest from
-- its entrance (dungeons whose farthest spot is under 30 m are left out: they go on through inner portals). The first use per character pays experience scaled to the dungeon's level (markers.json).
--   900500  Exploration Marker: a copy of retail's (39748) without its emotes, AcxExplorationMarker (bool 30006)
--   guids 0x7LLLLF30, one per dungeon landblock LLLL
-- Re-runnable. Restart the server after applying.

DELETE FROM landblock_instance WHERE weenie_Class_Id = 900500;
DELETE FROM weenie WHERE class_Id = 900500;

INSERT INTO weenie (class_Id, class_Name, type, last_Modified) SELECT 900500, 'acx-exploration-marker', type, NOW() FROM weenie WHERE class_Id = 39748;
INSERT INTO weenie_properties_int (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_int WHERE object_Id = 39748;
INSERT INTO weenie_properties_int64 (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_int64 WHERE object_Id = 39748;
INSERT INTO weenie_properties_float (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_float WHERE object_Id = 39748;
INSERT INTO weenie_properties_bool (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_bool WHERE object_Id = 39748;
INSERT INTO weenie_properties_string (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_string WHERE object_Id = 39748;
INSERT INTO weenie_properties_d_i_d (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_d_i_d WHERE object_Id = 39748;
INSERT INTO weenie_properties_i_i_d (object_Id, type, value) SELECT 900500, type, value FROM weenie_properties_i_i_d WHERE object_Id = 39748;
INSERT INTO weenie_properties_attribute (object_Id, `type`, `init_Level`, `level_From_C_P`, `c_P_Spent`) SELECT 900500, `type`, `init_Level`, `level_From_C_P`, `c_P_Spent` FROM weenie_properties_attribute WHERE object_Id = 39748;
INSERT INTO weenie_properties_attribute_2nd (object_Id, `type`, `init_Level`, `level_From_C_P`, `c_P_Spent`, `current_Level`) SELECT 900500, `type`, `init_Level`, `level_From_C_P`, `c_P_Spent`, `current_Level` FROM weenie_properties_attribute_2nd WHERE object_Id = 39748;
INSERT INTO weenie_properties_bool (object_Id, type, value) VALUES (900500, 30006, 1);   -- AcxExplorationMarker

INSERT INTO landblock_instance (guid, weenie_Class_Id, obj_Cell_Id, origin_X, origin_Y, origin_Z, angles_W, angles_X, angles_Y, angles_Z, is_Link_Child) VALUES
""" + "\n".join(rows) + "\n"
open(os.path.join(out_dir, "10-dungeon-markers.sql"), "w").write(sql)
print(f"{len(ok)} of {len(plan)} dungeons placed ({short} under {MIN_DISTANCE} m left out); skipped: " +
      ", ".join(sorted({d.get('status', '?') for d in plan if d.get('status') != 'ok'})))
