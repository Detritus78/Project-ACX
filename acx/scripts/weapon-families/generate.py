"""Project ACX: generate Factories/Tables/Wcids/AcxWeaponFamilies.cs, the plain / elemental / nether versions of each
loot weapon and caster, from the loot tables and the world DB. Salvage that changes a damage type gives the item the
look of the matching version (Managers/RecipeManager_Acx.cs). Run with the Preview DB up:
    python3 acx/scripts/weapon-families/generate.py"""
import collections, glob, re, subprocess, sys

SRC = '/home/jj/Work/ac/project-acx/Source/ACE.Server/Factories'
OUT = SRC + '/Tables/Wcids/AcxWeaponFamilies.cs'

def sql(q):
    r = subprocess.run(['docker', 'exec', '-i', 'acx-preview-db-1', 'sh', '-c', 'exec mysql -N -uroot -p"$MYSQL_ROOT_PASSWORD" ace_world'],
                       input=q, capture_output=True, text=True)
    return [line.split('\t') for line in r.stdout.strip().split('\n') if line]

enum = {m.group(1): int(m.group(2)) for m in re.finditer(r'^\s*(\w+)\s*=\s*(\d+),', open(SRC + '/Enum/WeenieClassName.cs').read(), re.M)}
names = set()
for f in glob.glob(SRC + '/Tables/Wcids/Weapons/*.cs'):
    names.update(re.findall(r'WeenieClassName\.(\w+)', open(f).read()))
ids = sorted(enum[n] for n in names if n in enum and n != 'undef')

rows = sql(f"""SELECT w.class_Id, s.value, COALESCE(d.value, 0) FROM weenie w
JOIN weenie_properties_string s ON s.object_Id = w.class_Id AND s.type = 1
LEFT JOIN weenie_properties_int d ON d.object_Id = w.class_Id AND d.type = 45
WHERE w.class_Id IN ({','.join(map(str, ids))}) OR w.class_Id BETWEEN 900100 AND 900199;""")

PREFIXES = ['Acid', 'Lightning', 'Electric', 'Flaming', 'Fire', 'Frost', 'Nether', 'Slashing', 'Piercing', 'Blunt']
DAMAGE = {1: 'Slash', 2: 'Pierce', 3: 'Slash | DamageType.Pierce', 4: 'Bludgeon', 8: 'Cold', 16: 'Fire', 32: 'Acid', 64: 'Electric', 1024: 'Nether'}

families = collections.defaultdict(list)
for wcid, name, dmg in rows:
    base, plain = name, True
    for p in PREFIXES:
        if name.startswith(p + ' '):
            base, plain = name[len(p) + 1:], False
            break
    families[base].append((int(wcid), int(dmg), plain, name))

families = {b: sorted(m, key=lambda x: (not x[2], x[0])) for b, m in families.items() if len(m) > 1 and any(x[1] in (8, 16, 32, 64) for x in m)}
# a family shares one name, so two plain items with the same name (quest copies) would be ambiguous: keep the first
for b, m in families.items():
    seen = set()
    families[b] = [x for x in m if not (x[2] and x[3] in seen) and not seen.add(x[3])]

# which looks differ inside families (to know what to copy)
member_ids = [x[0] for m in families.values() for x in m]
diff = collections.Counter()
for table in ['int', 'float', 'string', 'd_i_d']:
    for t, n in sql(f"""SELECT type, COUNT(*) FROM (SELECT f.type FROM weenie_properties_{table} f WHERE f.object_Id IN ({','.join(map(str, member_ids))})
        GROUP BY f.type, f.value) x GROUP BY type HAVING COUNT(*) > 1;"""):
        diff[f'{table} {t}'] = int(n)
print('properties that vary across family members:', dict(diff), file=sys.stderr)

lines = []
for base in sorted(families):
    lines.append(f'            // {base}')
    lines.append('            new[] { ' + ', '.join(f'({w}u, DamageType.{DAMAGE.get(d, "Undef")}, {"true" if p else "false"})' for w, d, p, _ in families[base]) + ' },')

open(OUT, 'w').write(f'''using System.Collections.Generic;

using ACE.Entity.Enum;

namespace ACE.Server.Factories.Tables.Wcids
{{
    /// <summary>
    /// Project ACX: the plain, elemental and nether versions of each loot weapon and caster ({len(families)} families), so salvage that
    /// changes a damage type can give the item the look of the matching version. Generated by acx/scripts/weapon-families/generate.py.
    /// </summary>
    public static class AcxWeaponFamilies
    {{
        private static readonly (uint Wcid, DamageType DamageType, bool Plain)[][] families =
        {{
{chr(10).join(lines)}
        }};

        private static readonly Dictionary<uint, (uint Wcid, DamageType DamageType, bool Plain)[]> familyByWcid = new Dictionary<uint, (uint, DamageType, bool)[]>();

        static AcxWeaponFamilies()
        {{
            foreach (var family in families)
            {{
                foreach (var member in family)
                    familyByWcid.TryAdd(member.Wcid, family);
            }}
        }}

        /// <summary>
        /// The version of this item's weapon with the damage type: the exact match, or for a physical type the plain version
        /// </summary>
        public static uint? GetVersion(uint wcid, DamageType damageType)
        {{
            if (!familyByWcid.TryGetValue(wcid, out var family))
                return null;

            foreach (var member in family)
            {{
                if (member.DamageType == damageType)
                    return member.Wcid;
            }}

            if ((damageType & DamageType.Physical) == 0)
                return null;

            foreach (var member in family)
            {{
                if (member.Plain)
                    return member.Wcid;
            }}

            return null;
        }}
    }}
}}
''')
print(f'{len(families)} families, {len(member_ids)} items -> {OUT}', file=sys.stderr)
